"""Semolina model classes for the canonical views."""

from __future__ import annotations

import textwrap
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from demo_stacks.semantic import Definitions, SemanticView

HEADER = '''"""
Semolina models for the {dataset} demo views.

Generated by `demo-stacks render` from semantic/{dataset}.yaml. Do not edit by hand.
"""

from semolina import Dimension, Fact, Metric, SemanticView
'''


def class_name(view: SemanticView) -> str:
    return "".join(part.capitalize() for part in view.name.split("_"))


def render(defs: Definitions) -> str:
    """One Python module holding a ``SemanticView`` subclass per view."""
    blocks = [HEADER.format(dataset=defs.dataset)]
    for view in defs.views:
        lines = [f'class {class_name(view)}(SemanticView, view="{view.name}"):']
        lines += ['    """', f"    The ``{view.name}`` semantic view."]
        if view.description:
            doc = textwrap.fill(" ".join(view.description.split()), width=92)
            lines += ["", textwrap.indent(doc, "    ")]
        lines += ['    """', ""]
        groups = [
            [f"    {f.name} = Fact()" for f in view.facts],
            [f"    {d.name} = Dimension()" for d in view.dimensions],
            [f"    {m.name} = Metric()" for m in view.metrics],
        ]
        lines += "\n\n".join("\n".join(g) for g in groups if g).split("\n")
        blocks.append("\n".join(lines) + "\n")
    return "\n\n".join(blocks)
